#include "tests.h"
#include "udev-builtin.h"

TEST(udev_builtin_cmd_to_ptr) {
        /* Those could have been static asserts, but ({}) is not allowed there. */
#if HAVE_BLKID
        ASSERT_NOT_NULL(UDEV_BUILTIN_CMD_TO_PTR(UDEV_BUILTIN_BLKID));
        ASSERT_EQ(PTR_TO_UDEV_BUILTIN_CMD(UDEV_BUILTIN_CMD_TO_PTR(UDEV_BUILTIN_BLKID)), UDEV_BUILTIN_BLKID);
#endif
        ASSERT_NOT_NULL(UDEV_BUILTIN_CMD_TO_PTR(UDEV_BUILTIN_BTRFS));
        ASSERT_EQ(PTR_TO_UDEV_BUILTIN_CMD(UDEV_BUILTIN_CMD_TO_PTR(UDEV_BUILTIN_BTRFS)), UDEV_BUILTIN_BTRFS);
        ASSERT_EQ(PTR_TO_UDEV_BUILTIN_CMD(UDEV_BUILTIN_CMD_TO_PTR(_UDEV_BUILTIN_INVALID)), _UDEV_BUILTIN_INVALID);

        ASSERT_EQ(PTR_TO_UDEV_BUILTIN_CMD(NULL), _UDEV_BUILTIN_INVALID);
        ASSERT_EQ(PTR_TO_UDEV_BUILTIN_CMD((void*) 10000), _UDEV_BUILTIN_INVALID);
}

DEFINE_TEST_MAIN(LOG_DEBUG);
