set -eux
set -o pipefail

# shellcheck source=test/units/generator-utils.sh
. "$(dirname "$0")/generator-utils.sh"

GENERATOR_BIN="/usr/lib/systemd/system-generators/systemd-firstboot-generator"
OUT_DIR="$(mktemp -d /tmp/firstboot-generator.XXX)"

at_exit() {
    rm -frv "${OUT_DIR:?}"
}

trap at_exit EXIT

if [[ ! -x "$GENERATOR_BIN" ]]; then
    echo "systemd-firstboot-generator not found, skipping the test"
    exit 77
fi

for cmdline in "" "systemd.firstboot=yes" "systemd.firstboot=headless systemd.firstboot=yes" "systemd.firstboot=invalid"; do
    : "firstboot-generator: '$cmdline' keeps the service on the console"
    SYSTEMD_PROC_CMDLINE="$cmdline" run_and_list "$GENERATOR_BIN" "$OUT_DIR"
    [[ "$(find "$OUT_DIR" ! -type d | wc -l)" -eq 0 ]]
done

for cmdline in "systemd.firstboot=headless" "systemd.firstboot=no"; do
    : "firstboot-generator: '$cmdline' detaches the service from the console"
    SYSTEMD_PROC_CMDLINE="$cmdline" run_and_list "$GENERATOR_BIN" "$OUT_DIR"
    diff - "$OUT_DIR/normal/systemd-firstboot.service.d/50-no-console.conf" <<EOF
# Automatically generated by systemd-firstboot-generator

[Service]
StandardInput=null
StandardOutput=journal+console
StandardError=journal+console
TTYReset=no
EOF
done
