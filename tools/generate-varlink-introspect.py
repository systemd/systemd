"""Generate the interface table for systemd-varlink-introspect.

Takes the list of Varlink IDL interface definition sources (as compiled into
libshared/libsystemd) and emits a C fragment with the necessary #include lines
and a table of all interfaces, sorted by interface name.

The file names double as the interface names they define:
'varlink-io.systemd.Foo.c' defines 'io.systemd.Foo', and the corresponding C
symbol is 'vl_interface_io_systemd_Foo'.
"""

import sys
from pathlib import Path

PREFIX = 'varlink-'
SUFFIX = '.c'


def interface_name(source: Path) -> str:
    stem = source.name
    if not stem.startswith(PREFIX) or not stem.endswith(SUFFIX):
        raise ValueError(f'{source} does not look like a Varlink IDL interface source')
    return stem[len(PREFIX):-len(SUFFIX)]


def c_symbol(name: str) -> str:
    return 'vl_interface_' + name.replace('.', '_')


def main() -> int:
    output = Path(sys.argv[1])
    sources = [Path(a) for a in sys.argv[2:]]

    interfaces = sorted(interface_name(s) for s in sources)
    if len(set(interfaces)) != len(interfaces):
        raise ValueError('duplicate interface definitions')

    lines = [
        '/* SPDX-License-Identifier: LGPL-2.1-or-later */',
        '/* Generated by tools/generate-varlink-introspect.py — do not edit. */',
        '',
        *(f'#include "{PREFIX}{name}.h"' for name in interfaces),
        '',
        'static const sd_varlink_interface* const varlink_idl_interfaces[] = {',
        *(f'        &{c_symbol(name)},' for name in interfaces),
        '};',
        '',
    ]

    output.write_text('\n'.join(lines))
    return 0


if __name__ == '__main__':
    sys.exit(main())
