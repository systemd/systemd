"""Updates the generated regions of the Varlink interface manual pages.

This mirrors tools/update-dbus-docs.py, but for Varlink: instead of talking to running
daemons, it invokes the build-time systemd-varlink-introspect tool, which dumps the IDL of
the interface definitions compiled into libshared/libsystemd (the single source of truth).

For each page it replaces
  - the contents of <programlisting varlink-interface="…"> with the canonical textual IDL,
  - the <variablelist class="varlink-*" generated="True" extra-ref="…"/> block between the
    Autogenerated markers, which feeds systemd.directives(7),
and leaves everything else (hand-written text) untouched.

With --scaffold, missing pages are created from a template first, so that newly added
interfaces can be bootstrapped.
"""

import argparse
import json
import os
import subprocess
import sys

try:
    from lxml import etree
except ModuleNotFoundError as e:
    etree = e

RED = '\x1b[31m'
GREEN = '\x1b[32m'
YELLOW = '\x1b[33m'
RESET = '\x1b[39m'

arguments = None


def xml_parser():
    return etree.XMLParser(no_network=True, remove_comments=False, strip_cdata=False, resolve_entities=False)


def run_introspect(*args):
    """Runs systemd-varlink-introspect from the build dir, returns stdout."""
    argv = [os.path.join(arguments.build_dir, 'systemd-varlink-introspect'), *args]
    try:
        return subprocess.check_output(argv, universal_newlines=True)
    except FileNotFoundError:
        print(f'{argv[0]} not found, ignoring', file=sys.stderr)
        return None


def interface_json(name):
    out = run_introspect('dump-json', name)
    if out is None:
        return None
    return json.loads(out)


def interface_idl(name):
    return run_introspect('dump', name)


def symbol_declarations(interface):
    """Returns [(kind, name)] for all symbols, in declaration order."""
    result = []
    for symbol in interface.get('symbols', []):
        result.append((symbol['kind'], symbol['name']))
    return result


CLASS_FOR_KIND = {
        'method': 'varlink-method',
        'type': 'varlink-type',
        'error': 'varlink-error',
}


def extra_ref_for(kind, name):
    # Methods are rendered with parentheses, mirroring the D-Bus convention for functions.
    return f'{name}()' if kind == 'method' else name


def subst_generated(document, programlisting, interface_name, stats):
    """Replaces the programlisting contents and the generated variablelist block."""
    idl = interface_idl(interface_name)
    if idl is None:
        return False
    interface = interface_json(interface_name)
    if interface is None:
        return False

    programlisting.text = '\n' + idl
    if not idl.endswith('\n'):
        programlisting.text += '\n'

    declarations = symbol_declarations(interface)
    stats['total'] += len(declarations)

    parent = programlisting.getparent()

    # Delete previously generated content: the marker comments and everything up to the
    # end marker.
    seen_start = False
    for child in list(parent):
        if child.tag is etree.Comment and 'Autogenerated cross-references' in (child.text or ''):
            seen_start = True
            parent.remove(child)
            continue
        if seen_start:
            parent.remove(child)
            if child.tag is etree.Comment and 'End of Autogenerated section' in (child.text or ''):
                break

    # Insert pointer for systemd.directives generation.
    the_tail = programlisting.tail  # tail is erased by addnext, so save it here.
    prev_element = etree.Comment('Autogenerated cross-references for systemd.directives, do not edit')
    programlisting.addnext(prev_element)
    programlisting.tail = the_tail

    def add_variablelist(klass, extra_ref):
        nonlocal prev_element
        variablelist = etree.Element('variablelist')
        variablelist.attrib['class'] = klass
        variablelist.attrib['generated'] = 'True'
        variablelist.attrib['extra-ref'] = extra_ref
        prev_element.addnext(variablelist)
        prev_element.tail = the_tail
        prev_element = variablelist

    add_variablelist('varlink-interface', interface_name)

    for kind, name in declarations:
        add_variablelist(CLASS_FOR_KIND[kind], extra_ref_for(kind, name))

    last_element = etree.Comment('End of Autogenerated section')
    prev_element.addnext(last_element)
    prev_element.tail = the_tail
    last_element.tail = the_tail

    return True


SCAFFOLD_TEMPLATE = '''\
<?xml version='1.0'?>
<!DOCTYPE refentry PUBLIC "-//OASIS//DTD DocBook XML V4.5//EN"
  "http://www.oasis-open.org/docbook/xml/4.5/docbookx.dtd" >
<!-- SPDX-License-Identifier: LGPL-2.1-or-later -->

<refentry id="{name}"
    xmlns:xi="http://www.w3.org/2001/XInclude">
  <refentryinfo>
    <title>{name}</title>
    <productname>systemd</productname>
  </refentryinfo>

  <refmeta>
    <refentrytitle>{name}</refentrytitle>
    <manvolnum>5</manvolnum>
  </refmeta>

  <refnamediv>
    <refname>{name}</refname>
    <refpurpose>{purpose}</refpurpose>
  </refnamediv>

  <refsect1>
    <title>Description</title>

    <para><interfacename>{name}</interfacename> is a Varlink interface implemented by
    <citerefentry><refentrytitle>systemd</refentrytitle><manvolnum>1</manvolnum></citerefentry>-related
    components. It can be introspected and called with
    <citerefentry><refentrytitle>varlinkctl</refentrytitle><manvolnum>1</manvolnum></citerefentry>.</para>

{description}
  </refsect1>

  <refsect1>
    <title>Interface Definition</title>

    <para>The following interface definition is exposed:</para>

    <programlisting varlink-interface="{name}"></programlisting>

    <!--Autogenerated cross-references for systemd.directives, do not edit-->

    <!--End of Autogenerated section-->
  </refsect1>

  <refsect1>
    <title>Examples</title>

    <para><screen>varlinkctl introspect <replaceable>SERVICE</replaceable> {name}</screen> shows the
    interface definition as served by <replaceable>SERVICE</replaceable>{example_call}</para>
  </refsect1>

  <refsect1>
    <title>See Also</title>
    <para><simplelist type="inline">
      <member><citerefentry><refentrytitle>varlinkctl</refentrytitle><manvolnum>1</manvolnum></citerefentry></member>
      <member><citerefentry><refentrytitle>systemd.varlink</refentrytitle><manvolnum>7</manvolnum></citerefentry></member>
      <member><citerefentry><refentrytitle>systemd.directives</refentrytitle><manvolnum>7</manvolnum></citerefentry></member>
    </simplelist></para>
  </refsect1>
</refentry>
'''


def escape(text):
    """Escapes text for inclusion in an XML document body."""
    return text.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')


def scaffold_page(path, interface):
    name = interface['name']
    comment = interface.get('comment')

    purpose = comment or f'Varlink interface {name}'
    description = ''
    if comment:
        description = f'    <para>{escape(comment)}</para>'

    methods = [s['name'] for s in interface.get('symbols', []) if s['kind'] == 'method']
    if methods:
        example_call = (
                f', and\n    <screen>varlinkctl call <replaceable>SERVICE</replaceable> '
                f'{name}.{methods[0]} \'{{}}\'</screen>\n    invokes its '
                f'<function>{methods[0]}</function> method.')
    else:
        example_call = '.'

    with open(path, 'w') as f:
        f.write(SCAFFOLD_TEMPLATE.format(
                name=name,
                purpose=escape(purpose),
                description=description,
                example_call=example_call))


def process(page):
    created = False
    if not os.path.exists(page):
        if arguments.scaffold:
            interface = interface_json(os.path.basename(page)[:-len('.xml')])
            if interface is None:
                return None
            scaffold_page(page, interface)
            created = True
        else:
            print(f'{page} does not exist', file=sys.stderr)
            return None

    src = open(page).read()
    xml = etree.fromstring(src, parser=xml_parser())

    if xml.tag != 'refentry':
        return None

    stats_dict['total'] = 0

    modified = created

    pls = xml.findall('.//programlisting[@varlink-interface]')
    for pl in pls:
        subst_generated(xml, pl, pl.get('varlink-interface'), stats_dict)

    out_text = etree.tostring(xml, encoding='unicode', pretty_print=False)
    # massage format to avoid some lxml whitespace handling idiosyncrasies
    # https://bugs.launchpad.net/lxml/+bug/526799
    out_text = src[: src.find('<refentryinfo')] + out_text[out_text.find('<refentryinfo') :] + '\n'

    modified = created or (out_text != src)

    if not arguments.test:
        with open(page, 'w') as out:
            out.write(out_text)

    return {'stats': stats_dict['total'], 'modified': modified}


stats_dict = {'total': 0}


def parse_args():
    p = argparse.ArgumentParser()
    p.add_argument(
            '--test',
            action='store_true',
            help='only verify that everything is up to date',
    )
    p.add_argument(
            '--scaffold',
            action='store_true',
            help='create missing pages before updating them',
    )
    p.add_argument(
            '--build-dir',
            default='build',
    )
    p.add_argument(
            'pages',
            nargs='+',
    )
    opts = p.parse_args()
    opts.print_errors = not opts.test
    return opts


def main():
    global arguments
    arguments = parse_args()

    if isinstance(etree, Exception):
        print(etree, file=sys.stderr)
        sys.exit(77 if arguments.test else 1)

    if not os.path.exists(f'{arguments.build_dir}'):
        sys.exit(f"{arguments.build_dir} doesn't exist.")

    stats = {}
    for page in arguments.pages:
        result = process(page)
        if result is not None:
            stats[page.split('/')[-1]] = result

    total = sum(info['stats'] for info in stats.values())
    modified = [page for page, info in sorted(stats.items()) if info['modified']]
    classification = 'OUTDATED' if arguments.test else 'MODIFIED'

    mlen = max(len(page) for page in stats) if stats else 0
    for page, info in sorted(stats.items()):
        c = classification if info['modified'] else ''
        color = GREEN if not info['modified'] else YELLOW
        print(f'{color}{page + ":":{mlen + 1}} {info["stats"]} {c}{RESET}')
    print(f'total: {total}')

    if arguments.test and modified:
        sys.exit(
                f'Outdated pages: {", ".join(modified)}\n'
                f'Hint: ninja -C {arguments.build_dir} update-varlink-docs'
        )  # fmt: skip


if __name__ == '__main__':
    main()
